# PrescriptionMed Serializer (nested create/update)
# -------------------------
class PrescriptionMedSerializer(serializers.ModelSerializer):
    # Use PK fields for related models so client sends IDs only (lightweight).
    consultation_id = serializers.PrimaryKeyRelatedField(
        queryset=ConsultationNotes.objects.all()
    )
   
    staff_id = serializers.PrimaryKeyRelatedField(read_only=True)

    # `details` is write-only input for nested creation/update of PrescriptionMedDetail rows.
    # It expects a list of objects matching PrescriptionMedDetailSerializer.
    details = PrescriptionMedDetailSerializer(many=True, write_only=True)

    # `details_out` is the read-only representation of detail rows when returning a prescription.
    # We point the source to the reverse accessor generated by Django:
    # prescription.prescriptionmeddetail_set.all() -> source 'prescriptionmeddetail_set'.
    # details_out = PrescriptionMedDetailSerializer(source="prescriptionmeddetail_set", many=True, read_only=True)

    class Meta:
        model = PrescriptionMed
        fields = [
            "prescription_auto_id",   # DB auto PK
            "prescription_med_id",    # generated code like PMED001
            "consultation_id",
            
            "staff_id",
            "created_at",
            "details",    # write-only nested input
            # "details_out" # read-only nested output
        ]
        # auto-generated and timestamps should be read-only
        read_only_fields = ("prescription_auto_id", "prescription_med_id", "staff_id", "created_at")

    # Object-level validation example: require at least one medicine detail on create.
    def validate(self, attrs):
        details = attrs.get("details", [])
        if not details:
            raise serializers.ValidationError("At least one medicine must be provided.")
        medicine_ids = [detail["medicine"] for detail in details]
        if len(medicine_ids) != len(set(medicine_ids)):
            raise serializers.ValidationError("Duplicate medicines are not allowed.")
        # Ensure consultation and appointment match
        
        return attrs
    # create() handles nested creation of PrescriptionMedDetail rows.
    @transaction.atomic
    def create(self, validated_data):
        details_data = validated_data.pop("details", [])
        try:
            prescription = PrescriptionMed.objects.create(**validated_data)
            for detail in details_data:
                PrescriptionMedDetail.objects.create(prescription=prescription, **detail)
            return prescription
        except IntegrityError as e:
            raise serializers.ValidationError({"error": f"Database error: {str(e)}"})
        except Exception as e:
            raise serializers.ValidationError({"error": f"Unexpected error: {str(e)}"})



