# ConsultationNotes Serializer
# -------------------------
class ConsultationNotesSerializer(serializers.ModelSerializer):
    # Use PrimaryKeyRelatedField so API accepts/returns the appointment's primary key (ID)
    # rather than embedding the entire appointment object.
    appointment_id = serializers.PrimaryKeyRelatedField(
        queryset=Appointment.objects.all()
    )
    # Same for staff: accept/validate an integer staff PK.
    staff_id = serializers.PrimaryKeyRelatedField(
        queryset=Staff.objects.all()
    )
    
    prescriptions_med = PrescriptionMedSerializer(
        source="prescriptionmed_set",  # Django reverse relation
        many=True,
        required=False
    )
    prescriptions_lab = PrescriptionLabSerializer(
        source="prescriptionlab_set",  # Django reverse relation
        many=True,
        required=False
    )

    class Meta:
        # Model this serializer is for
        model = ConsultationNotes
        # fields to expose via API
        fields = "__all__"
        # These fields are set by the model/save logic, don't allow client to set them
        read_only_fields = ("consultation_auto_id", "consultation_id", "created_at")

    # Field-level validation: ensures symptoms has some meaningful length.
    def validate_symptoms(self, value):
        if value is None or len(value.strip()) < 3:
            raise serializers.ValidationError("Provide a brief description of symptoms (3+ chars).")
        return value
    
    # Optional: only one consultation per appointment
    def validate_appointment_id(self, value):
        if ConsultationNotes.objects.filter(appointment_id=value).exists():
            raise serializers.ValidationError("A consultation already exists for this appointment.")
        return value

    # Object-level validation: ensure diagnosis or notes is present (example business rule).
    def validate(self, data):
        # This runs after individual field validators. The API must have either a diagnosis
        # or notes (so consultations aren't empty).
        diagnosis = data.get("diagnosis", "")
        notes = data.get("notes", "")
        if (diagnosis is None or str(diagnosis).strip() == "") and (notes is None or str(notes).strip() == ""):
            raise serializers.ValidationError("Either 'diagnosis' or 'notes' must be provided.")
        return data

